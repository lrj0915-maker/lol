// 按ID查找
export function getChampionById(id) {
  return champions.find(c => c.id === id)
}

// 按名称搜索（支持中英文和昵称）
export function searchChampions(keyword) {
  if (!keyword) return champions
  const kw = keyword.toLowerCase()
  return champions.filter(c => 
    c.name.toLowerCase().includes(kw) || 
    c.nameEn.toLowerCase().includes(kw) ||
    c.key.toLowerCase().includes(kw) ||
    (c.aliases && c.aliases.some(alias => alias.toLowerCase().includes(kw)))
  )
}

export default champions
